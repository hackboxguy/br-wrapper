#!/usr/bin/env python3
"""qvue-bench.py - 983/988 bench status for FPD-Link IV video bring-up.

One command:

    sudo python3 -u qvue-bench.py status

Prints, in pipeline order, what is needed to decide whether a mode left the
Pi, crossed the HDMI-to-DP bridge, was regenerated by the DS90UH983 and
arrived at the deserializer:

    RH850            983_manager firmware version and build stamp via 0x67
    983 VP           VP_STS_VP0 (bit 0 = timing generator synced) + INTR_STS
    983 DP input     MSA active/total, and the pixel clock from M/N at the
                     trained link rate
    983 VP output    programmed VP0 H total
    983 I2C          pass-through and the target-alias slot (0x07/0x70/0x78/0x88)
    deserializer     GP_STATUS_0/1 lock bits
    deser measured   the timing the deserializer actually measures at its input

Display-agnostic on purpose: it reads generic 983/988 registers and takes no
display-type argument, so the same output is meaningful for any panel on the
bench.  Needs only smbus2.

Two indirect-page conventions are in use on this bus and both are mirrored
here exactly as their proven source does it, rather than unified:

  * the 983 side follows otsctl.py / the kernel driver, which write
    IND_ACC_CTL = (page << 2) | 1, i.e. a shifted page number plus the read
    strobe (VP page 0x0C -> 0x31);
  * the deserializer measured-timing block follows fpdlink-tool.sh, which
    writes the raw BIOS-script page byte with no strobe (DTG page -> 0x50).

They address the same hardware; keeping each call shaped like the tool it was
taken from means a disagreement here is a real difference, not a transcription
error.
"""

import subprocess
import sys
import time

from smbus2 import SMBus

SER = 0x18          # DS90UH983 serializer, local address after RH850 init
DES = 0x2C          # deserializer alias on the local bus (988 or 984)
RH = 0x67           # 983_manager status slave

bus = SMBus(1, force=True)


def rd(addr, reg):
    return bus.read_byte_data(addr, reg)


def wr(addr, reg, val):
    bus.write_byte_data(addr, reg, val)


def rd_opt(addr, reg):
    """Read, or None if the device does not answer."""
    try:
        return rd(addr, reg)
    except OSError:
        return None


# --- 983 indirect: shifted page + read strobe (otsctl.py / driver convention)
def ind_ser(page, off):
    wr(SER, 0x40, (page << 2) | 1)
    wr(SER, 0x41, off)
    return rd(SER, 0x42)


# --- deserializer indirect: raw page byte (fpdlink-tool.sh convention)
def ind_des(page_byte, off):
    wr(DES, 0x40, page_byte)
    wr(DES, 0x41, off)
    return rd(DES, 0x42)


def ind_des15_be(page_byte, msb_off, lsb_off):
    """15-bit big-endian: MSB[6:0] at msb_off, LSB[7:0] at lsb_off."""
    msb = ind_des(page_byte, msb_off)
    lsb = ind_des(page_byte, lsb_off)
    return ((msb & 0x7F) << 8) | lsb


def apb(addr, reg):
    """32-bit APB read through the indirect APB window."""
    wr(addr, 0x48, 0x01)
    wr(addr, 0x49, reg & 0xFF)
    wr(addr, 0x4A, (reg >> 8) & 0xFF)
    wr(addr, 0x48, 0x03)
    time.sleep(0.001)
    return rd(addr, 0x4B) | (rd(addr, 0x4C) << 8) | (rd(addr, 0x4D) << 16) | (rd(addr, 0x4E) << 24)


# DP link symbol rate in MHz per DPCD LINK_BW_SET code.
LINK_RATE_MHZ = {0x06: 162.0, 0x0A: 270.0, 0x14: 540.0, 0x1E: 810.0}

# Plausible frame rates for anything on this bench; used to infer the trained
# link rate (see infer_pclk).
REFRESH_MIN, REFRESH_MAX = 45.0, 85.0


def infer_pclk(adv_rate, mvid, nvid, h_tot, v_tot):
    """Return (pclk_MHz, link_rate_MHz, how) for the DP stream clock.

    fstream = fLS * Mvid / Nvid, where fLS is the *trained* link symbol rate.
    APB 0x074 is MAX_LINK_RATE -- what the sink advertises it can do, not what
    the link trained at -- and nothing in the 983's APB 0x000..0x11C range was
    found to expose the trained rate as a code.  Measured on this bench
    2026-09-12: a 1920x1080 @ 136.687 MHz stream reported 0x074 = 0x14 (HBR2)
    while Mvid/Nvid only reconciles with fLS = 270 MHz (HBR).  Assuming the
    advertised rate -- as otsctl.py does -- reports exactly double there.

    So infer instead: try every rate at or below the advertised maximum and
    keep the one whose implied frame rate is plausible for the MSA totals.
    """
    adv_ls = LINK_RATE_MHZ.get(adv_rate)
    if not (adv_ls and nvid and h_tot and v_tot):
        return 0.0, None, "insufficient data"

    fits = []
    for ls in sorted(LINK_RATE_MHZ.values()):
        if ls > adv_ls:
            continue
        pclk = ls * mvid / nvid
        refresh = pclk * 1e6 / (h_tot * v_tot)
        if REFRESH_MIN <= refresh <= REFRESH_MAX:
            fits.append((pclk, ls, refresh))

    if len(fits) == 1:
        pclk, ls, refresh = fits[0]
        return pclk, ls, "trained rate inferred as %g MHz -> %.2f Hz" % (ls, refresh)
    if not fits:
        pclk = adv_ls * mvid / nvid
        return pclk, adv_ls, "no rate gives a plausible frame rate; assuming advertised %g MHz" % adv_ls
    return fits[0][0], fits[0][1], "ambiguous (%s)" % ", ".join("%g MHz" % f[1] for f in fits)


def rh_read(reg, n):
    """Read n bytes from the 0x67 16-bit sub-addressed slave."""
    cmd = ["sudo", "i2ctransfer", "-y", "-f", "1",
           "w2@0x%02x" % RH, "0x%02x" % (reg >> 8), "0x%02x" % (reg & 0xFF),
           "r%d@0x%02x" % (n, RH)]
    try:
        r = subprocess.run(cmd, capture_output=True, text=True, timeout=5)
    except subprocess.TimeoutExpired:
        return []
    return [int(x, 16) for x in r.stdout.split()] if r.returncode == 0 else []


def status():
    # ---- RH850
    v = rh_read(0x0000, 8)
    if len(v) == 8:
        print("RH850  0x67   : fw %02x.%02x  built 20%02x-%02x-%02x %02x:%02x"
              % (v[0], v[1], v[3], v[4], v[5], v[6], v[7]))
    else:
        print("RH850  0x67   : no answer")

    # ---- 983 video processor
    try:
        vp_sts = ind_ser(0x0C, 0x30)
        vp_intr = ind_ser(0x0C, 0x31)
        prog_htot = ind_ser(0x0C, 0x16) | (ind_ser(0x0C, 0x17) << 8)
    except OSError as exc:
        print("983    VP     : read failed (%s)" % exc)
        return 1

    print("983    VP     : VP_STS=0x%02x (%s)  INTR_STS=0x%02x"
          % (vp_sts, "SYNCED" if vp_sts & 0x01 else "NOT synced", vp_intr))

    # ---- 983 DP input (MSA) and the recovered pixel clock
    rate = apb(SER, 0x074)
    h_act, v_act = apb(SER, 0x500), apb(SER, 0x514)
    h_tot, v_tot = apb(SER, 0x510), apb(SER, 0x524)
    mvid, nvid = apb(SER, 0x530), apb(SER, 0x534)
    pclk, ls, how = infer_pclk(rate, mvid, nvid, h_tot, v_tot)
    print("983    DP in  : MSA %dx%d  Htot %d  Vtot %d  pclk %.2f MHz"
          % (h_act, v_act, h_tot, v_tot, pclk))
    print("               MAX_LINK_RATE(0x074)=0x%02X (advertised %s)  Mvid %d  Nvid %d"
          % (rate, ("%g MHz" % LINK_RATE_MHZ[rate]) if rate in LINK_RATE_MHZ else "unknown",
             mvid, nvid))
    print("               %s" % how)

    # ---- 983 VP output
    print("983    VP out : programmed H total %d (0x%04X)" % (prog_htot, prog_htot))

    # ---- 983 I2C control and target-alias slot 0
    regs = {r: rd_opt(SER, r) for r in (0x07, 0x70, 0x78, 0x88)}
    print("983    I2C    : PASS_THROUGH(0x07)=%s  TARGET_ID0(0x70)=%s  "
          "ALIAS0(0x78)=%s  DEST0(0x88)=%s"
          % tuple("0x%02X" % regs[r] if regs[r] is not None else "--"
                  for r in (0x07, 0x70, 0x78, 0x88)))
    if regs[0x70] is not None and regs[0x78] is not None:
        print("               -> remote 7-bit 0x%02X presented to the host as 0x%02X"
              % (regs[0x70] >> 1, regs[0x78] >> 1))

    # ---- deserializer link status
    s0, s1 = rd_opt(DES, 0x53), rd_opt(DES, 0x54)
    if s0 is None or s1 is None:
        print("DES    0x%02X   : no answer" % DES)
        return 1
    print("DES    0x%02X   : GP_STATUS_0=0x%02X GP_STATUS_1=0x%02X  [%s%s%s]"
          % (DES, s0, s1,
             "FPD4_LOCK " if s0 & 0x01 else "",
             "SIG_DET " if s1 & 0x02 else "",
             "LOCK" if s1 & 0x01 else "NO_LOCK"))

    # ---- deserializer measured input timing (fpdlink-tool.sh --timings offsets)
    try:
        m_htot = ind_des15_be(0x50, 0x40, 0x41)
        m_vtot = ind_des15_be(0x50, 0x42, 0x43)
        m_hact = ind_des15_be(0x50, 0x44, 0x45)
        m_vact = ind_des15_be(0x50, 0x46, 0x47)
    except OSError as exc:
        print("DES    meas   : read failed (%s)" % exc)
        return 1
    print("DES    meas   : active %dx%d  total %dx%d" % (m_hact, m_vact, m_htot, m_vtot))

    # ---- the one line that says whether the pipeline agrees end to end
    if prog_htot and m_htot:
        delta = abs(m_htot - prog_htot)
        print("VERDICT       : 983 programmed H total %d vs deserializer measured %d "
              "(delta %d) -> %s" % (prog_htot, m_htot, delta,
                                    "MATCH" if delta <= 32 else "MISMATCH / DTG wedged"))
    return 0


def main():
    cmd = sys.argv[1] if len(sys.argv) > 1 else "status"
    if cmd != "status":
        print("usage: qvue-bench.py status", file=sys.stderr)
        return 2
    return status()


if __name__ == "__main__":
    sys.exit(main())
